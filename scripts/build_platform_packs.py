def parse_skill(md_path: Path) -> dict:
    raw = md_path.read_text(encoding="utf-8")
    fm, body = split_frontmatter_text(raw)
    name = ""
    description = ""
    nm = re.search(r"^name:\s*(.+)$", fm, re.M)
    if nm:
        name = nm.group(1).strip()
    dm = re.search(r"^description:\s*(.+)$", fm, re.M)
    if dm:
        description = dm.group(1).strip()
    h1 = re.search(r"^#\s+(.+)$", body, re.M)
    if not name and h1:
        name = h1.group(1).strip()
    section_names = [m.group(1).strip()
                     for m in re.finditer(r"^##\s+(.+)$", body, re.M)]
    return {
        "name": name, "description": description, "raw": raw, "body": body,
        "section_names": section_names,
    }


CMD_ROW = re.compile(
    r"^\|\s*`(/[^`]+)`\s*\|\s*`(skills/[^`]+?/SKILL\.md)`\s*\|(.+)\|\s*$")


def load_commands() -> dict:
    commands: dict[str, dict] = {}
    if not COMMANDS_FILE.is_file():
        return commands
    for line in COMMANDS_FILE.read_text(encoding="utf-8").split("\n"):
        m = CMD_ROW.match(line.strip())
        if not m:
            continue
        cells = [c.strip() for c in m.group(3).split("|")]
        commands[m.group(2)] = {
            "command": m.group(1),
            "triggers": cells[0] if len(cells) > 0 else "",
            "inputs": cells[1] if len(cells) > 1 else "",
            "output": cells[2] if len(cells) > 2 else "",
        }
    return commands


def is_safe_module_id(value: object) -> bool:
    """Return whether an ID is safe in manifests and archive member names."""
    return isinstance(value, str) and re.fullmatch(
        r"[a-z0-9][a-z0-9-]*", value
    ) is not None


def load_areas() -> dict:
    areas: dict[str, dict] = {}
    for area_dir in sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir()):
        area = area_dir.name
        skills = []
        for sd in sorted(p for p in area_dir.iterdir() if p.is_dir()):
            if sd.name == "references":
                continue
            md = sd / "SKILL.md"
            if not md.is_file():
                continue
            sk = parse_skill(md)
            sk["slug"] = sd.name
            sk["area"] = area
            sk["path"] = f"skills/{area}/{sd.name}/SKILL.md"
            sk["spec_path"] = None
            sk["spec_raw"] = ""
            sk["spec"] = {}
            sk["module_resources"] = []
            for required in REQUIRED_SECTIONS:
                if required not in sk["section_names"]:
                    err(f"skill {sk['path']} is missing required section "
                        f"'## {required}'")
            required_present = [s for s in sk["section_names"]
                                if s in REQUIRED_SECTIONS]
            if (set(required_present) == set(REQUIRED_SECTIONS)
                    and required_present != REQUIRED_SECTIONS):
                err(f"skill {sk['path']} has its required sections out of order")
            templates = []
            tdir = sd / "templates"
            if tdir.is_dir():
                for f in sorted(tdir.iterdir()):
                    if f.is_file():
                        templates.append((f.name, f.read_text(encoding="utf-8")))
            sk["templates"] = templates

            spec_path = sd / "SPEC.json"
            if spec_path.is_file():
                spec_rel = spec_path.relative_to(REPO_ROOT).as_posix()
                spec_raw = spec_path.read_text(encoding="utf-8")
                try:
                    spec = json.loads(spec_raw)
                except json.JSONDecodeError as exc:
                    err(f"skill {sk['path']} has invalid {spec_rel}: {exc}")
                    spec = {}
                if not isinstance(spec, dict):
                    err(f"skill {sk['path']} has a non-object {spec_rel}")
                    spec = {}
                sk["spec_path"] = spec_rel
                sk["spec_raw"] = spec_raw
                sk["spec"] = spec
                for module in spec.get("modules", []):
                    if not isinstance(module, dict):
                        err(f"skill {sk['path']} has a non-object module record")
                        continue
                    module_id = module.get("id")
                    module_path = module.get("path")
                    if not is_safe_module_id(module_id):
                        err(
                            f"skill {sk['path']} has an unsafe module id: "
                            f"{module_id!r}"
                        )
                        continue
                    if not isinstance(module_path, str) or not module_path:
                        err(f"skill {sk['path']} module '{module_id}' has no path")
                        continue
                    resolved = (REPO_ROOT / module_path).resolve()
                    if not resolved.is_relative_to(REPO_ROOT.resolve()):
                        err(
                            f"skill {sk['path']} module '{module_id}' escapes "
                            f"the repository root: {module_path}"
                        )
                        continue
                    if not resolved.is_file():
                        err(
                            f"skill {sk['path']} module '{module_id}' target "
                            f"is missing: {module_path}"
                        )
                        continue
                    resource = dict(module)
                    resource["content"] = resolved.read_text(encoding="utf-8")
                    sk["module_resources"].append(resource)
            skills.append(sk)
        references = []
        rdir = area_dir / "references"
        if rdir.is_dir():
            for f in sorted(rdir.iterdir()):
                if f.is_file() and f.suffix == ".md":
                    references.append((f.name, f.read_text(encoding="utf-8")))
        if skills:
            areas[area] = {"skills": skills, "references": references}
    return areas


